ON public.admins FOR SELECT 
TO anon, authenticated 
USING (true);

DROP POLICY IF EXISTS "Allow update admins" ON public.admins;
CREATE POLICY "Allow update admins" 
ON public.admins FOR UPDATE 
TO anon, authenticated 
